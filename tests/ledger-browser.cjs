// Run against the dev server backed by ledger-fixture-server.cjs, never production.
const assert = require('node:assert/strict');
const fs = require('node:fs');
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
async function main() {
  const browser = await chromium.connectOverCDP(process.env.LEDGER_TEST_CDP);
  const context = browser.contexts()[0];
  const page = context.pages().find((p) => p.url().startsWith('http://127.0.0.1:4321'));
  assert.ok(page, 'Open the local ledger with agent-browser first');
  const errors = [];
  page.on('pageerror', (e) => errors.push(e.message));
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto('http://127.0.0.1:4321/ledger');
  await page.waitForFunction(() => [...document.querySelectorAll('astro-island')].every((island) => !island.hasAttribute('ssr')));
  await page.getByRole('button', { name: '设置', exact: true }).click();
  await page.getByPlaceholder('输入 API Key').fill('ledger-local-test-only');
  await page.getByRole('button', { name: '保存', exact: true }).click();
  await page.getByRole('button', { name: '记一笔', exact: true }).click();
  const dialog = page.getByRole('dialog');
  await dialog.getByLabel('实付金额（元） *', { exact: true }).fill('16.25');
  await dialog.getByLabel('品牌', { exact: false }).fill('测试品牌');
  await dialog.getByLabel('商品 *', { exact: true }).fill('测试奶瓶 240ml');
  await dialog.getByRole('button', { name: '🍼 喂养用品', exact: true }).click();
  await dialog.getByLabel('时间', { exact: true }).fill('2026-09-08T00:00');
  await dialog.getByLabel('备注', { exact: false }).fill('店铺：测试店,A\n订单号：00000012345678901234\n优惠：店铺优惠¥15');
  const box = await dialog.boundingBox();
  assert.ok(box.x >= 0 && box.x + box.width <= 391 && box.height <= 844, 'Mobile dialog fits viewport');
  if (process.env.LEDGER_SCREENSHOT) await page.screenshot({ path: process.env.LEDGER_SCREENSHOT, fullPage: true });
  const savedResponse = page.waitForResponse((r) => r.url().endsWith('/api/add') && r.request().method() === 'POST');
  await dialog.getByRole('button', { name: '保存账单', exact: true }).click();
  const saved = await (await savedResponse).json();
  assert.equal(saved.success, true);
  assert.equal(saved.data.amount, 16.25);
  assert.equal(saved.data.brand, '测试品牌');
  assert.equal(saved.data.product, '测试奶瓶 240ml');
  assert.ok(saved.data.note.includes('00000012345678901234'));
  await page.getByRole('tab', { name: '历史', exact: true }).click();
  const search = page.getByPlaceholder('搜索品牌、商品、备注、分类或金额...');
  await search.fill('测试品牌');
  const row = page.getByRole('button', { name: /测试品牌 · 测试奶瓶 240ml/ });
  await row.click();
  assert.ok((await dialog.innerText()).includes('00000012345678901234'));
  await dialog.getByRole('button', { name: '编辑', exact: true }).click();
  await dialog.getByLabel('品牌', { exact: false }).fill('');
  await dialog.getByLabel('备注', { exact: false }).fill('');
  await dialog.getByLabel('商品 *', { exact: true }).fill('修改后奶瓶');
  const editedResponse = page.waitForResponse((r) => r.url().endsWith('/api/edit') && r.request().method() === 'PATCH');
  await dialog.getByRole('button', { name: '保存账单', exact: true }).click();
  const edited = await (await editedResponse).json();
  assert.equal(edited.data.brand, null);
  assert.equal(edited.data.note, null);
  assert.equal(edited.data.product, '修改后奶瓶');
  assert.equal(edited.data.amount, 16.25);
  await search.fill('修改后奶瓶');
  const downloadPromise = page.waitForEvent('download');
  await page.getByRole('button', { name: '导出 CSV' }).click();
  const download = await downloadPromise;
  const csv = fs.readFileSync(await download.path(), 'utf8');
  assert.ok(csv.includes('品牌,商品,分类,备注') && csv.includes('修改后奶瓶'));
  await search.fill('旧账单');
  await page.getByRole('button', { name: /旧账单，时间未知/ }).click();
  await dialog.getByRole('button', { name: '编辑', exact: true }).click();
  assert.equal(await dialog.getByLabel('时间', { exact: true }).inputValue(), '');
  await dialog.getByLabel('备注', { exact: false }).fill('旧账单补充备注');
  const legacyResponse = page.waitForResponse((r) => r.url().endsWith('/api/edit') && r.request().method() === 'PATCH');
  await dialog.getByRole('button', { name: '保存账单', exact: true }).click();
  assert.equal((await (await legacyResponse).json()).data.transaction_time, null);
  const headers = { Authorization: 'Bearer ledger-local-test-only' };
  const partial = await page.request.patch('http://127.0.0.1:4321/api/edit', { headers, data: { id: saved.data.id, note: '仅改备注' } });
  assert.equal((await partial.json()).data.product, '修改后奶瓶');
  const invalid = await page.request.post('http://127.0.0.1:4321/api/add', { headers, data: { amount: null, type: 'expense' } });
  assert.equal(invalid.status(), 400);
  const unauthenticated = await page.request.post('http://127.0.0.1:4321/api/add', { data: { amount: 1, type: 'expense' } });
  assert.equal(unauthenticated.status(), 401);
  const absent = await page.request.patch('http://127.0.0.1:4321/api/edit', { headers, data: { id: '00000000-0000-0000-0000-000000000000', note: 'x' } });
  assert.equal(absent.status(), 404);
  const old = await page.request.post('http://127.0.0.1:4321/api/add', { headers, data: { amount: 5, type: 'expense', note: '旧格式调用' } });
  assert.equal((await old.json()).success, true);
  await page.goto('http://127.0.0.1:4321/blog/bill-skill');
  assert.ok(await page.getByRole('heading', { name: '账单 skill', exact: true }).count());
  await page.setViewportSize({ width: 1280, height: 900 });
  await page.goto('http://127.0.0.1:4321/ledger');
  await page.waitForFunction(() => [...document.querySelectorAll('astro-island')].every((island) => !island.hasAttribute('ssr')));
  await page.getByRole('button', { name: '记一笔', exact: true }).click();
  assert.ok(await page.getByLabel('商品 *', { exact: true }).isVisible());
  await page.getByRole('button', { name: '取消', exact: true }).click();
  assert.deepEqual(errors, []);
  console.log('PASS: mobile/desktop forms, create/read/edit, clear fields, legacy unknown time, search, CSV, API validation/auth/404, article; no page errors.');
  await browser.close();
}
main().catch((error) => { console.error(error); process.exit(1); });
